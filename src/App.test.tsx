// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('online marketplace product risk office', () => {
  it('loads product risk cases from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'Illegal toy listing risk assessment', owner: 'European Marketplace Safety Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('Illegal toy listing risk assessment')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Online Marketplace Product Risk Office' })).toBeTruthy()
  })
})
